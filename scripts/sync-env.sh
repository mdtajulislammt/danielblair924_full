#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# 🛡️ Avengerse Central Environment Synchronizer (scripts/sync-env.sh)
# Distributes credentials from root .env / .env.example into:
#   1. development/backend/.env
#   2. development/frontend/.env.local
#   3. development/mobile/.env
# ==============================================================================

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

SOURCE_ENV=".env"

# If root .env does not exist, initialize from .env.example
if [ ! -f "$SOURCE_ENV" ]; then
  if [ -f ".env.example" ]; then
    echo "ℹ️  Root .env not found. Initializing .env from .env.example..."
    cp .env.example .env
  else
    echo "❌ Error: Neither .env nor .env.example found in root directory!"
    exit 1
  fi
fi

echo "🔄 Reading centralized configuration from: $SOURCE_ENV"

# Helper to read an env variable value from SOURCE_ENV
get_env_val() {
  local key="$1"
  local default_val="${2:-}"
  local val
  val=$(grep -E "^${key}=" "$SOURCE_ENV" | cut -d '=' -f2- | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//" | head -n 1)
  if [ -z "$val" ]; then
    echo "$default_val"
  else
    echo "$val"
  fi
}

NODE_ENV=$(get_env_val "NODE_ENV" "development")
BACKEND_PORT=$(get_env_val "BACKEND_PORT" "4000")
FRONTEND_PORT=$(get_env_val "FRONTEND_PORT" "3000")
DATABASE_URL=$(get_env_val "DATABASE_URL" "postgresql://postgres:postgres@localhost:5432/app_db?schema=public")
REDIS_URL=$(get_env_val "REDIS_URL" "redis://localhost:6379")
JWT_SECRET=$(get_env_val "JWT_SECRET" "change_me_super_secret_jwt_access_key")
JWT_REFRESH_SECRET=$(get_env_val "JWT_REFRESH_SECRET" "change_me_super_secret_jwt_refresh_key")
JWT_EXPIRES_IN=$(get_env_val "JWT_EXPIRES_IN" "15m")
JWT_REFRESH_EXPIRES_IN=$(get_env_val "JWT_REFRESH_EXPIRES_IN" "7d")
CORS_ORIGIN=$(get_env_val "CORS_ORIGIN" "http://localhost:3000")

S3_ENDPOINT=$(get_env_val "S3_ENDPOINT" "")
S3_REGION=$(get_env_val "S3_REGION" "us-east-1")
S3_BUCKET=$(get_env_val "S3_BUCKET" "app-uploads")
S3_ACCESS_KEY_ID=$(get_env_val "S3_ACCESS_KEY_ID" "")
S3_SECRET_ACCESS_KEY=$(get_env_val "S3_SECRET_ACCESS_KEY" "")

NEXT_PUBLIC_API_URL=$(get_env_val "NEXT_PUBLIC_API_URL" "http://localhost:${BACKEND_PORT}/api/v1")
NEXT_PUBLIC_APP_NAME=$(get_env_val "NEXT_PUBLIC_APP_NAME" "Avengerse App")
NEXT_PUBLIC_APP_ENV=$(get_env_val "NEXT_PUBLIC_APP_ENV" "$NODE_ENV")

MOBILE_API_BASE_URL=$(get_env_val "MOBILE_API_BASE_URL" "http://10.0.2.2:${BACKEND_PORT}/api/v1")
MOBILE_APP_ENV=$(get_env_val "MOBILE_APP_ENV" "$NODE_ENV")

# ------------------------------------------------------------------------------
# 1. Sync Backend Environment (development/backend/.env)
# ------------------------------------------------------------------------------
BACKEND_DIR="development/backend"
if [ -d "$BACKEND_DIR" ]; then
  BACKEND_ENV="${BACKEND_DIR}/.env"
  cat <<EOF > "$BACKEND_ENV"
# Auto-generated by scripts/sync-env.sh from root .env
NODE_ENV=${NODE_ENV}
PORT=${BACKEND_PORT}
DATABASE_URL=${DATABASE_URL}
REDIS_URL=${REDIS_URL}
JWT_SECRET=${JWT_SECRET}
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}
JWT_EXPIRES_IN=${JWT_EXPIRES_IN}
JWT_REFRESH_EXPIRES_IN=${JWT_REFRESH_EXPIRES_IN}
CORS_ORIGIN=${CORS_ORIGIN}
S3_ENDPOINT=${S3_ENDPOINT}
S3_REGION=${S3_REGION}
S3_BUCKET=${S3_BUCKET}
S3_ACCESS_KEY_ID=${S3_ACCESS_KEY_ID}
S3_SECRET_ACCESS_KEY=${S3_SECRET_ACCESS_KEY}
EOF
  echo "  ✅ Synced: ${BACKEND_ENV} (Port: ${BACKEND_PORT})"
fi

# ------------------------------------------------------------------------------
# 2. Sync Frontend Environment (development/frontend/.env.local)
# ------------------------------------------------------------------------------
FRONTEND_DIR="development/frontend"
if [ -d "$FRONTEND_DIR" ]; then
  FRONTEND_ENV="${FRONTEND_DIR}/.env.local"
  cat <<EOF > "$FRONTEND_ENV"
# Auto-generated by scripts/sync-env.sh from root .env
NODE_ENV=${NODE_ENV}
PORT=${FRONTEND_PORT}
NEXT_PUBLIC_API_URL=${NEXT_PUBLIC_API_URL}
NEXT_PUBLIC_APP_NAME=${NEXT_PUBLIC_APP_NAME}
NEXT_PUBLIC_APP_ENV=${NEXT_PUBLIC_APP_ENV}
EOF
  echo "  ✅ Synced: ${FRONTEND_ENV} (Port: ${FRONTEND_PORT})"
fi

# ------------------------------------------------------------------------------
# 3. Sync Mobile Environment (development/mobile/.env)
# ------------------------------------------------------------------------------
MOBILE_DIR="development/mobile"
if [ -d "$MOBILE_DIR" ]; then
  MOBILE_ENV="${MOBILE_DIR}/.env"
  cat <<EOF > "$MOBILE_ENV"
# Auto-generated by scripts/sync-env.sh from root .env
APP_ENV=${MOBILE_APP_ENV}
API_BASE_URL=${MOBILE_API_BASE_URL}
EOF
  echo "  ✅ Synced: ${MOBILE_ENV}"
fi

echo ""
echo "🎉 SUCCESS: All environment credentials distributed automatically from root!"
echo "   - Backend:  http://localhost:${BACKEND_PORT}"
echo "   - Frontend: http://localhost:${FRONTEND_PORT}"
